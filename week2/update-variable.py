def main():
    #augmented assignment operator
    score = 10
    score += 10
    print(score)

    #subtraction assignment operator
    sub = 100
    sub -= 15
    print(sub)

    #multiplication assignment operator
    mult = 10
    mult *= 4
    print(mult)

    #division assignment operator
    div = 10
    div /= 4
    print(div)

    #modulo assignment operator
    a = 10
    b = 4
    a %= b
    print(a)

